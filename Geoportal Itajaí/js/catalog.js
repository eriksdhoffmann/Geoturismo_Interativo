  // Utilitário para construir URL codificada de serviço ArcGIS REST
  function buildServiceUrl(servicePath) {
    const encoded = servicePath
      .split('/')
      .map((seg) => encodeURIComponent(seg))
      .join('/');
    return `${ARCGIS_BASE}/${encoded}`;
  }

  function getLayerById(id) {
    for (const g of LAYER_GROUPS) {
      const found = g.layers.find((l) => l.id === id);
      if (found) return { layer: found, group: g };
    }
    return null;
  }

  function getAllLayers() {
    const out = [];
    for (const g of LAYER_GROUPS) {
      for (const l of g.layers) out.push({ ...l, groupId: g.id, groupName: g.name });
    }
    return out;
  }

